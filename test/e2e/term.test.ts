// エージェント用の端末操作経路（term デーモン）と run-scenario を実プロセス/PTYで検証する。
import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { cli, waitFor } from "../helpers/cli.ts";
import { ROOT, TODO } from "../helpers/project.ts";
import { pidAlive } from "../../src/store.ts";

test("term: start→press/paste→wait→screen(--style)→resize→restart で保存確認→stop、履歴と証拠が残る", async () => {
  const root = mkdtempSync(join(tmpdir(), "kenshu-term-e2e-"));
  const app = join(ROOT, "examples", "todo-tui");
  const T = (...a: string[]) => cli(["term", "--root", root, ...a]);
  const start = T("start", "--name", "s1", "--cols", "40", "--rows", "10", "--cwd", app, "--", "node", "todo.mjs");
  assert.equal(start.code, 0, start.stderr);
  const sj = JSON.parse(start.stdout);
  assert.match(sj.screen, /項目がありません/);
  const pid = Number(readFileSync(join(root, "s1", "daemon.pid"), "utf8"));
  assert.ok(pidAlive(pid));
  assert.equal(T("press", "--name", "s1", "a").code, 0);
  const paste = JSON.parse(T("paste", "--name", "s1", "とても長い日本語のタスク名を貼り付けて狭い端末で確認する").stdout);
  assert.equal(paste.record.actual, "bracketed paste");
  assert.equal(T("press", "--name", "s1", "Enter").code, 0);
  assert.equal(T("wait", "--name", "s1", "追加しました").code, 0);
  const miss = T("wait", "--name", "s1", "存在しない文字列", "--timeout", "300");
  assert.equal(miss.code, 1, "見つからなければ ok:false / exit 1");
  const scr = JSON.parse(T("screen", "--name", "s1", "--style").stdout);
  assert.match(scr.screen, /\[ \] とても長い日本語のタスク名を貼り付…/);
  assert.ok(scr.styled.some((r: { style: { inverse?: boolean }; text: string }) => r.style.inverse && r.text.includes("とても長い")));
  const st = T("step", "--name", "s1", JSON.stringify({ do: "expect_style", text: "TODO (1件)", style: { bold: true } }));
  assert.equal(st.code, 0, st.stdout);
  assert.equal(T("resize", "--name", "s1", "24", "8").code, 0);
  const narrow = JSON.parse(T("screen", "--name", "s1").stdout);
  assert.match(narrow.screen, /size=24x8/);
  assert.equal(T("capture", "--name", "s1", "narrow").code, 0);
  assert.equal(T("press", "--name", "s1", "q").code, 0);
  assert.equal(T("step", "--name", "s1", JSON.stringify({ do: "wait_exit", exit_code: 0 })).code, 0);
  assert.equal(T("restart", "--name", "s1").code, 0);
  assert.equal(T("wait", "--name", "s1", "TODO (1件)").code, 0, "再起動後も保存されている");
  assert.equal(T("stop", "--name", "s1").code, 0);
  await waitFor(() => !pidAlive(pid), 5000, "daemon exit");
  const hist = readFileSync(join(root, "s1", "history.jsonl"), "utf8").trim().split("\n").map((l) => JSON.parse(l));
  assert.ok(hist.length >= 10);
  assert.equal(hist.at(-1).op, "shutdown");
  assert.ok(existsSync(join(root, "s1-home", ".todo-tui.json")), "隔離HOMEに保存される");
  const after = T("screen", "--name", "s1");
  assert.equal(after.code, 1, "停止後は接続エラー");
  assert.match(after.stderr, /接続できません/);
});

test("term run-scenario: 正常版は exit 0、不具合版は失敗ステップと期待/実際を報告して exit 1", () => {
  const out = mkdtempSync(join(tmpdir(), "kenshu-sc-"));
  const sc = join(ROOT, "examples", "todo-tui", "scenario.json");
  const ok = cli(["term", "run-scenario", sc, "--cwd", join(ROOT, "examples", "todo-tui"), "--out", join(out, "ok")]);
  assert.equal(ok.code, 0, ok.stdout + ok.stderr);
  const bugDir = mkdtempSync(join(tmpdir(), "kenshu-bug-"));
  writeFileSync(join(bugDir, "todo.mjs"), readFileSync(TODO, "utf8").replace("const BUGS = [];", 'const BUGS = ["notruncate"];'));
  const bad = cli(["term", "run-scenario", sc, "--cwd", bugDir, "--out", join(out, "bad")]);
  assert.equal(bad.code, 1);
  const j = JSON.parse(bad.stdout);
  assert.equal(j.status, "fail");
  assert.match(j.failure, /step \d+ \(wait_text\)/);
  const res = JSON.parse(readFileSync(j.result, "utf8"));
  const failed = res.steps.at(-1);
  assert.equal(failed.ok, false);
  assert.ok(failed.screen.length === 8, "失敗時点の現在画面を記録");
  const invalid = cli(["term", "run-scenario", join(ROOT, "package.json")]);
  assert.equal(invalid.code, 1);
  assert.match(invalid.stderr, /シナリオが不正/);
});
